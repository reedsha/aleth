"""Canned deliverable source written by the Coder delegation path.

The registry does not call an LLM for these tasks: it classifies the task's shape
and writes a fixed, runnable module plus its test. Keeping that source here means
the generated bytes are auditable in one place instead of sitting in the middle of
the workflow's control flow, and they can be tested without driving a whole
workflow.
"""

from typing import NamedTuple, Optional

from tools.task_tags import UI_TAG, UI_KEYWORD_RE


# ``UI_KEYWORD_RE`` is defined in ``tools.task_tags`` (matched on word boundaries) and
# re-exported here so the template selector, the plan parser and Laya's domain tagger all
# read one vocabulary -- no second word list that could drift from the selector's. It
# lives in the vocabulary module rather than here so that building the parser's tag
# vocabulary does not have to import the orchestration package on the cold-start path.


class Deliverable(NamedTuple):
    """A generated module together with the test written next to it."""

    filename: str
    test_filename: str
    code: str
    test_code: str



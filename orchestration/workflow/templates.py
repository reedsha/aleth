def _solution_engine(header: str, result_key: str, result_value: str) -> str:
    """The `SolutionEngine` module, differing only in its header and echoed input."""
    return f'''{header}
from typing import Dict, Any

class SolutionEngine:
    def __init__(self, config: Dict[str, Any] = None):
        self.config = config or {{}}

    def run(self) -> Dict[str, Any]:
        return {{
            "{result_key}": "{result_value}",
            "status": "success",
            "verified": True
        }}

if __name__ == "__main__":
    engine = SolutionEngine()
    print("Execution output:", engine.run())
'''


def ui_view() -> Deliverable:
    """Glassmorphic HTML view for a UI-shaped task."""
    return Deliverable("ui_view.html", "test_ui_view.py", _UI_VIEW_HTML, _UI_VIEW_TEST)


def weather_api() -> Deliverable:
    """FastAPI weather service for a task whose title mentions weather."""
    return Deliverable("weather_api.py", "test_weather_api.py", _WEATHER_API, _WEATHER_API_TEST)


def default_engine(label: str) -> Deliverable:
    """The catch-all `main.py` module for a task with no more specific shape."""
    return Deliverable(
        "main.py", "test_main.py",
        _solution_engine(f'# Generated module for task: {label}', "task", label),
        SOLUTION_ENGINE_TEST
    )


def custom_engine(message: str) -> Deliverable:
    """The `main.py` module written in response to a free-form custom directive."""
    return Deliverable(
        "main.py", "test_main.py",
        _solution_engine(f"# Custom Solution: {message[:60]}", "prompt", message),
        SOLUTION_ENGINE_TEST
    )


def select(task_title: str, tag: Optional[str] = None) -> Deliverable:
    """Picks the template matching a task's declared shape.

    The task's domain tag decides the UI case. The title is deliberately not re-inspected
    for UI wording: the parser already turns a UI-shaped title into the tag, so a second
    inference here would be a second source of truth -- one that could pick the HTML view
    while the plan tree draws no pill, which is exactly the drift this replaced.

    Order is significant: a UI task beats the weather keyword, and anything
    unmatched falls through to the generic engine.
    """
    lowered = task_title.lower()
    if tag == UI_TAG:
        return ui_view()
    if "weather" in lowered:
        return weather_api()
    return default_engine(task_title)
